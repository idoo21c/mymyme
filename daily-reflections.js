  function date(now) {
    return new Date((now == null ? Date.now() : now) + seoulOffsetMs).toISOString().slice(0, 10);
  }

  function dayIndex(dateStr) {
    return (Date.parse(dateStr) - Date.parse(start)) / dayMs;
  }

  function cardOn(dateStr) {
    var entry = cards[dayIndex(dateStr)];
    return entry ? { quote: entry[0], question: entry[1], source: entry[2] || '' } : null;
  }

  function daysUntilLastCard(dateStr) {
    return cards.length - 1 - dayIndex(dateStr);
  }

